#!/usr/bin/env python3
"""Generate kmr-vectors.json: snp-kmr-v1 runtime-register vectors.

An implementation independent of mr.rs (stdlib only). Run from this
directory: python3 kmr-vectors.py > kmr-vectors.json
"""
import hashlib
import json

TAG = b"snp-kmr-v1"
REGISTERS = 16


def sha384(data):
    return hashlib.sha384(data).digest()


def entry(index, name):
    return bytes([index]) + sha384(name.encode())


def replay(log, count):
    registers = [bytes(48)] * REGISTERS
    for i in range(count):
        e = log[i * 49 : (i + 1) * 49]
        registers[e[0]] = sha384(registers[e[0]] + e[1:])
    return registers


def report_data(count, registers, caller_data):
    h = count.to_bytes(4, "little") + bytes(12)
    return h + sha384(TAG + h + b"".join(registers) + caller_data)


def vector(name, caller_data, log, count):
    registers = replay(log, count)
    return {
        "name": name,
        "caller_data": caller_data.hex(),
        "event_log": log.hex(),
        "event_count": count,
        "registers": [r.hex() for r in registers],
        "report_data": report_data(count, registers, caller_data).hex(),
    }


def rejected(name, caller_data, log, reported, expect):
    return {
        "name": name,
        "caller_data": caller_data.hex(),
        "event_log": log.hex(),
        "report_data": reported.hex(),
        "expect": expect,
    }


# A relying party's 64 bytes: a nonce and a key hash, as an example.
caller = sha384(b"nonce")[:32] + hashlib.sha256(b"public key").digest()
four = (
    entry(0, "rootfs")
    + entry(1, "modules latched")
    + entry(0, "rootfs again")
    + entry(15, "last register")
)
five = four + entry(4, "workload")
four_rd = bytes.fromhex(vector("", caller, four, 4)["report_data"])


def with_byte(data, offset, value):
    return data[:offset] + bytes([value]) + data[offset + 1 :]


print(
    json.dumps(
        {
            "format": "snp-kmr-v1 runtime registers, generated by kmr-vectors.py. Hex strings. event_log: raw concatenated 49-byte entries (u8 register index || 48-byte digest); event_count: entries the report commits to; registers: R[0..15] after replaying that prefix from zero; report_data: H || C. rejected: expect \"malformed\" (an error, whatever the header says) or \"mismatch\" (not this commitment).",
            "vectors": [
                vector("genesis", bytes(range(64)), b"", 0),
                vector("genesis_zero_caller_data", bytes(64), b"", 0),
                vector("four_events", caller, four, 4),
                vector("prefix_of_longer_log", caller, five, 4),
                vector("five_events", caller, five, 5),
            ],
            "rejected": [
                rejected("index_above_15", caller, with_byte(four, 3 * 49, 16), four_rd, "malformed"),
                rejected("index_above_15_past_the_count", caller, five[: 4 * 49] + entry(16, "workload"), four_rd, "malformed"),
                rejected("trailing_partial_entry", caller, four + b"\x00", four_rd, "malformed"),
                rejected("log_shorter_than_the_count", caller, four[: 3 * 49], four_rd, "mismatch"),
                rejected("nonzero_header_padding", caller, four, with_byte(four_rd, 15, 1), "mismatch"),
                rejected("reordered_within_a_register", caller, four[2 * 49 : 3 * 49] + four[49 : 2 * 49] + four[:49] + four[3 * 49 :], four_rd, "mismatch"),
                rejected("other_caller_data", with_byte(caller, 63, caller[63] ^ 1), four, four_rd, "mismatch"),
            ],
        },
        indent=1,
    )
)
